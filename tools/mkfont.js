// 1文字を5バイト(列ごと、bit0が上)にする
export function glyphColumns(rows) {
  const cols = [];
  for (let x = 0; x < 5; x++) {
    let b = 0;
    for (let y = 0; y < 7; y++) if (rows[y][x] === '#') b |= 1 << y;
    cols.push(b);
  }
  return cols;
}

function generate() {
  const lines = ['; 5×7フォント(tools/mkfont.js が生成。手で直さないこと)', '; $20-$7E の95文字 × 5バイト', 'font:'];
  for (let c = 0x20; c <= 0x7e; c++) {
    const ch = String.fromCharCode(c);
    const rows = GLYPHS[ch];
    if (!rows || rows.length !== 7 || rows.some((r) => r.length !== 5)) throw new Error(`bad glyph: ${ch}`);
    const bytes = glyphColumns(rows).map((b) => '$' + b.toString(16).toUpperCase().padStart(2, '0'));
    lines.push(`        .byte ${bytes.join(', ')}   ; $${c.toString(16).toUpperCase()} ${ch}`);
  }
  return lines.join('\n') + '\n';
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(join(root, 'rom/font.s'), generate());
  console.log('rom/font.s written');
}
